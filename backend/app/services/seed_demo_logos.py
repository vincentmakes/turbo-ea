def house_logo_path(stem: str) -> Path:
    """On-disk path of a house mark. Exposed so tests can assert it exists."""
    return HOUSE_LOGO_DIR / f"{stem}.png"


# ===================================================================
# Public entry point
# ===================================================================
SEEDER_KEY = "logos"


async def seed_logo_demo_data(db: AsyncSession) -> dict:
    """Attach demo card logos to existing NexaTech Applications / IT Components.

    Cards are matched by exact name and silently skipped when absent, so the
    seeder stays compatible with a partial-demo install — the same contract
    ``seed_demo_security`` keeps.

    Note what this deliberately does **not** do: it writes no card event and
    never touches ``cards.updated_at``. That falls out of ``card_logos`` being
    a side table (see ``app/models/card_logo.py``), which is exactly why the
    Inventory **Modified** column keeps meaning "content last changed" — a
    seeded logo must not re-date three hundred cards.
    """
    if await demo_seed_completed(db, SEEDER_KEY):
        return {"skipped": True, "reason": "already seeded"}

    # Legacy guard for installs that seeded before this seeder existed: logos
    # are only created here, so any row means we already ran. Record the marker
    # now so the install stops relying on the inference.
    existing = await db.execute(select(CardLogo.id).limit(1))
    if existing.scalar_one_or_none() is not None:
        await mark_demo_seed_completed(db, SEEDER_KEY)
        await db.commit()
        return {"skipped": True, "reason": "card logos already exist"}

    admin_result = await db.execute(select(User.id).where(User.role == "admin").limit(1))
    admin_id = admin_result.scalar_one_or_none()
    if admin_id is None:
        return {"skipped": True, "reason": "no admin user found"}

    # Only types that actually offer logos. Checking here means the seeder can
    # never create a row `POST /cards/{id}/logo` would itself have refused.
    allowed_types = set(
        (await db.execute(select(CardType.key).where(CardType.allow_card_logo.is_(True))))
        .scalars()
        .all()
    )
    if not allowed_types:
        return {"skipped": True, "reason": "no card type allows logos"}

    card_rows = await db.execute(select(Card.id, Card.name, Card.type))
    name_to_id: dict[str, uuid.UUID] = {
        row.name: row.id for row in card_rows.all() if row.type in allowed_types
    }

    brand_count = 0
    house_count = 0

    for card_name, ref in BRAND_LOGOS:
        card_id = name_to_id.get(card_name)
        if not card_id:
            continue
        resolved = resolve_brand_icon(ref)
        if resolved is None:
            # A ref the packs no longer carry. The unit tests pin every ref, so
            # this is a torn pack rather than a bad mapping — skip the card
            # rather than abort the whole demo seed over one icon.
            continue
        data, _mime, _entry = resolved
        db.add(
            CardLogo(
                id=uuid.uuid4(),
                card_id=card_id,
                mime_type=BRAND_ICON_MIME,
                size=len(data),
                data=data,
                created_by=admin_id,
            )
        )
        brand_count += 1

    for card_name, stem in HOUSE_LOGOS:
        card_id = name_to_id.get(card_name)
        if not card_id:
            continue
        path = house_logo_path(stem)
        try:
            data = path.read_bytes()
        except OSError:
            continue
        db.add(
            CardLogo(
                id=uuid.uuid4(),
                card_id=card_id,
                mime_type=HOUSE_LOGO_MIME,
                size=len(data),
                data=data,
                created_by=admin_id,
            )
        )
        house_count += 1

    await db.flush()
    await mark_demo_seed_completed(db, SEEDER_KEY)
    await db.commit()
    return {
        "brand_logos": brand_count,
        "house_logos": house_count,
    }
