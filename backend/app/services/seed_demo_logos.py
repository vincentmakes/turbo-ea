"""NexaTech Industries demo — card logos.

Puts a product's own mark on the demo Applications and IT Components, so a
fresh ``SEED_DEMO=true`` boot shows the card-logo feature rather than a wall of
identical type icons: the card header, the Inventory **Logo** column, published
web portals, DrawIO diagrams and the Layered Dependency View all render one.

Two sources, no network:

``BRAND_LOGOS``
    Real products, resolved by slug out of the bundled brand-icon packs
    (``app/services/brand_icons.py``). The pack ships inside the image, so this
    works on an air-gapped install exactly as it does anywhere else.
``HOUSE_LOGOS``
    NexaTech's own software, which by construction has no mark in the world.
    Generated by ``frontend/scripts/gen-demo-logos.mjs`` into ``data/demo_logos``
    and committed.

**Not every card gets one, deliberately.** Roughly a third keep their card-type
icon, in two groups that are both honest outcomes rather than gaps to paper
over: brands the CC0 packs do not carry (ServiceNow, Workday, DocuSign, Coupa,
Altium, MATLAB…), and generic internal services and shadow IT — giving *Sales
Contact Workbook* a polished logo would misrepresent what it is. A landscape
where some cards have marks and some do not is what a real one looks like, and
it exercises the fallback the feature actually ships.

Idempotent via the durable marker in ``app_settings.general_settings.demoSeeded``
(see ``seed_markers``), so deleting a logo never brings it back on the next
restart. A separate seeder key rather than an addition to ``seed_demo_extras``
precisely because extras is already marked complete on every existing demo
install and would never run again.
"""

